def extract_between(text: str, start: str, end: str) -> str:
    """Return the substring of ``text`` from marker ``start`` up to marker ``end``.

    Both markers must occur exactly once and in order. The returned region
    includes ``start`` and excludes ``end`` — matching the region boundaries
    used to compute the frozen phase hashes.

    Args:
        text: The full text to slice.
        start: A marker that appears exactly once, marking the region start.
        end: A marker that appears exactly once after ``start``, ending it.

    Returns:
        The substring ``text[start_index:end_index]``.

    Raises:
        AssertionError: If either marker is missing, non-unique, or out of order.
    """
    assert text.count(start) == 1, f"start marker not unique ({text.count(start)}): {start!r}"
    assert text.count(end) == 1, f"end marker not unique ({text.count(end)}): {end!r}"
    s = text.index(start)
    e = text.index(end)
    assert s < e, f"markers out of order: {start!r} must precede {end!r}"
    return text[s:e]


