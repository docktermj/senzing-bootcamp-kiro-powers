def sha256_bytes(data: bytes) -> str:
    """Return the hex SHA-256 digest of raw bytes.

    Args:
        data: The bytes to hash.

    Returns:
        The lowercase hex SHA-256 digest.
    """
    return hashlib.sha256(data).hexdigest()


