class TestNonTargetSteeringFilesByteIdentity:
    """Every non-target steering ``.md`` file stays byte-identical after the fix.

    **Property 3: Preservation — Non-Target Steering Files Unchanged**

    The frozen SHA-256 baseline is compared against the current bytes. The
    property (PBT) samples over the file set; the exhaustive deterministic test
    guarantees full coverage of all files regardless of the active Hypothesis
    example count.

    **Validates: Requirements 3.5, 3.6**
    (other single-👉 paths — onboarding, mid-module, feedback, graduation — and
    the compound-question rewrite rule live in these unchanged files)
    """

    @given(name=st_non_target_steering_file())
    def test_non_target_steering_file_matches_frozen_hash(self, name: str) -> None:
        """A sampled non-target steering file's bytes match the frozen baseline."""
        path = STEERING_DIR / name
        assert path.exists(), f"non-target steering file went missing: {name}"
        actual = sha256_bytes(path.read_bytes())
        assert actual == FROZEN_STEERING_SHA256[name], (
            f"{name} drifted from the frozen baseline: {actual} "
            f"!= {FROZEN_STEERING_SHA256[name]}"
        )

    def test_all_non_target_steering_files_match_frozen_hashes(self) -> None:
        """ALL non-target steering files match their frozen baseline (exhaustive)."""
        drift: list[str] = []
        for name, expected in sorted(FROZEN_STEERING_SHA256.items()):
            path = STEERING_DIR / name
            if not path.exists():
                drift.append(f"{name}: MISSING (expected {expected})")
                continue
            actual = sha256_bytes(path.read_bytes())
            if actual != expected:
                drift.append(f"{name}: {actual} != {expected}")
        assert not drift, "Non-target steering files drifted:\n" + "\n".join(drift)

    def test_non_target_steering_file_set_matches_frozen(self) -> None:
        """The on-disk non-target ``.md`` set equals the frozen baseline set.

        Catches an added or removed steering file that the byte-identity hashes
        alone would miss (a new file has no frozen entry; a deleted one leaves a
        stale entry).
        """
        on_disk = {
            p.name for p in STEERING_DIR.glob("*.md") if p.name not in EXCLUDED_STEERING
        }
        frozen = set(FROZEN_STEERING_SHA256)
        assert on_disk == frozen, (
            f"non-target steering file set changed; "
            f"added={sorted(on_disk - frozen)} removed={sorted(frozen - on_disk)}"
        )

    def test_excluded_files_are_the_only_edited_targets(self) -> None:
        """The excluded set is exactly the fix's edited/regenerated steering ``.md``."""
        assert EXCLUDED_STEERING == frozenset(
            {
                "module-completion.md",
                "module-completion-next-steps.md",
                "module-transitions.md",
                "hook-registry-critical.md",
            }
        )
        for name in EXCLUDED_STEERING:
            assert (STEERING_DIR / name).exists(), f"expected edited target missing: {name}"


